export function partnerOf(lead: Kid): Kid {
  return lead === 'boy' ? 'girl' : 'boy'
}

/** 장면 번호 — 예: sceneId('astronaut', '03') → 'A-03' */
export function sceneId(job: JobId, scene: string): string {
  return `${SCRIPTS[job].prefix}-${scene}`
}

/**
 * 문장 시범 장면 — 문장 ①은 10, ②는 13.
 * 만 6세 이상은 문장 뜻이 달라 따로 그린 b 장면이 있으면 그것 (시나리오 §3).
 */
export function lineScene(job: JobId, turn: 0 | 1, older: boolean): string {
  const base = turn === 0 ? '10' : '13'
  return older && SCRIPTS[job].scenes[`${base}b`] ? `${base}b` : base
}
