import type { JobId } from '@shared/types'

export type Kid = 'boy' | 'girl'
export type Who = Kid | 'both'

export interface JobScript {
  /** 장면 번호 앞 글자 */
  prefix: string
  /** 이끄는 캐릭터 — 짝꿍은 나머지 */
  lead: Kid
  /** 위 제목 — em 부분 밑에 분홍 붓질 (시안: "우주로 [출발]해 볼까요?") */
  title: { before: string; em: string; after: string }
  /** 직업마다 다른 대사 */
  lines: {
    /** A · 이끔 — 인사 */
    hello: string
    /** A · 짝꿍 — 역할 주기 */
    role: string
    /** B · 이끔 — 임무 (아이 목소리가 꼭 필요한 이유) */
    mission: string
    /** E 크게 · 짝꿍 */
    loud: string
    /** E 작게 · 짝꿍 — 탓은 이야기 속 대상에게 */
    quiet: string
    /** E 무음 · 이끔 — "한 번만 더, 준비 완료!"로 끝난다 */
    silent: string
    /** 다시 말하기 · 짝꿍 (뒤에 이끔이 COMMON.retryLead) */
    retry: string
    /** G · 짝꿍 — 이야기가 한 걸음 나아간다 */
    bridge: string
    /** I · 둘이 같이 — 마무리 */
    outro: string
  }
  /** 장면 설명 — 그림이 오기 전 임시 판에 적는다 (시나리오 §2 표의 "장면" 칸) */
  scenes: Record<string, string>
}

