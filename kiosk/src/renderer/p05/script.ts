/**
 * 레이어 장면 (2026-11-24) — 배경 판 하나 + 여자아이 · 남자아이 포즈 그림 (assets/p05/layers/<직업>/<이름>.webp).
 * 배경이 같은 장면끼리는 인물 포즈만 스르르 바뀌고, 배경이 바뀌면 장면째 옆으로 넘어간다.
 * 장면 '00' = 대사 없이 먼저 보이는 장면 (둘이 이야기하다가 → 아이를 돌아보며 인사로)
 */
export interface LayeredScene {
  bg: string
  girl: string
  boy: string
  /** 배경 위 · 인물 뒤에 놓는 소품 (2026-11-26 — 로켓 · 별 · 행성을 배경에서 빼고 따로 받음) */
  props?: readonly SceneProp[]
  /**
   * 목소리 게이지 — 그림 위 오른쪽에 크게 덮어 그린다 (0 = 빈 채 ~ 1 = 꽉 참 · 없으면 안 보임).
   * 2026-11-26: 로켓 문 속 작은 게이지 → 로켓과 따로, 눈에 띄게 크게 (사용자 지정)
   */
  gauge?: number
  /**
   * 게이지 자리 — 배경 그림 픽셀(소품과 같은 기준): 가운데 x · 폭 · 위 · 아래.
   * 없으면 그림 오른쪽 끝에 판 높이만큼 (CSS 기본). 2026-11-26 — 로켓 옆에 로켓과 같은 길이로 붙여 "로켓에 차는 게이지"로 보이게
   */
  gaugeBox?: { cx: number; w: number; top: number; bottom: number }
  /** 이 장면에서만 인물 키를 바꿀 때 (기본 1 — 발끝은 그대로, 헬멧 가운데 기준) */
  scale?: { girl?: number; boy?: number }
  /**
   * 이 장면에서만 인물이 서는 가로 자리 (판 폭 대비 · 헬멧 가운데 — 기본 여 0.36 · 남 0.595).
   * A-04부터 두 아이가 살짝 멀어져 가운데에 마이크 자리를 연다 (2026-11-26 사용자 지정 — 그 전 장면은 그대로)
   */
  cast?: { girl?: number; boy?: number }
  /** 가운데 마이크가 대사 내내 빛난다 ("띵!" 신호 · 녹음 때와 같은 빛 — 2026-11-26 A-04-2) */
  micOn?: boolean
  /** 목소리 게이지가 반짝반짝 — 후광이 빨리 숨 쉬고 둘레에 별빛이 반짝 (게이지를 가리키는 장면 — 2026-11-26 A-04-2) */
  gaugeShine?: boolean
  /**
   * 하이파이브 — 마주친 손끝에서 금빛 선 세 개가 뽀오옹 뻗고, 이어서 별 세 개가 땽! 튀어나온다 (2026-11-27 A-07).
   * 손끝 자리(cx · cy)와 효과 크기(w)는 배경 그림 픽셀. 별 그림은 `prop-sparkle`, 선은 앱이 그린다
   */
  burst?: { cx: number; cy: number; w: number }
}

/**
 * 소품 한 개 — 그림 `layers/<직업>/<img 또는 name>.webp` (투명 여백을 잘라 둔 그림). name은 장면 사이에서 같은 소품을 알아보는 이름.
 * 자리는 **배경 그림 픽셀**(bg-moon 1910 × 823) 기준: 가운데(cx · cy)와 폭(w). 높이는 그림 비율대로.
 * 같은 배경의 다음 장면에도 같은 이름이 있으면 그 자리로 스르르 옮겨 가고(크기도), 없어지면 사라지고, 새로 생기면 나타난다.
 */
export interface SceneProp {
  name: string
  /** 그림 이름 (없으면 name) — 같은 그림을 여러 개 놓을 때 */
  img?: string
  cx: number
  cy: number
  w: number
  /**
   * glow = 노란 빛 번짐 · twinkle = 반짝반짝(빛이 커졌다 작아졌다)
   * mic = 가운데 마이크 — 둥실 떠 있고, "띵!" 신호 · 녹음 중에는 `<그림>-glow`(빛나는 마이크)로 바뀌며 두근 (2026-11-26)
   */
  fx?: 'glow' | 'twinkle' | 'mic'
  /** 돌기를 멈춘다 — 그 자리 그 각도에서 (반짝임은 그대로 · 2026-11-26 새 별은 가리키는 A-03이 끝나면 그만 돈다) */
  still?: boolean
  /** 반짝반짝 빛난다 — 금빛 빛 번짐이 숨 쉬고 둘레에 별빛이 번갈아 (2026-11-26 A-04-2 로켓 — 게이지와 같이) */
  shine?: boolean
}

export interface JobScript {
  /** 장면 번호 앞 글자 */
  prefix: string
  /** 이끄는 캐릭터 — 짝꿍은 나머지 */
  lead: Kid
  /** 위 제목 — em 부분 밑에 분홍 붓질 (시안: "우주로 [출발]해 볼까요?") */
  title: { before: string; em: string; after: string }
  /** 직업마다 다른 대사 */
  lines: {
    /** A · 이끔 — 인사 */
    hello: string
    /** A · 짝꿍 — 역할 주기 */
    role: string
    /**
     * B · 이끔 — 임무 (아이 목소리가 꼭 필요한 이유).
     * 길면 자막을 여러 개로 나눌 수 있다 — 나눈 대사마다 그림(scene, 없으면 03)을 정한다. 진행 바는 한 칸만 쓴다.
     * 목소리 파일 이름: 하나면 mission · 나누면 mission-1 · mission-2 …
     */
    mission: string | { text: string; scene?: string }[]
    /**
     * C · 짝꿍 — 목소리 게이지 소개 (게이지가 있는 직업만 · 2026-11-26 우주비행사).
     * 진짜 띵을 들려준 뒤 · 시범 전에 장면 04-2에서 — 목소리 파일 이름 gauge.
     * 문장마다 자막을 나누면 목소리 파일도 gauge-1 · gauge-2 … (2026-11-26 우주비행사)
     */
    gauge?: string | readonly string[]
    /** E 크게 · 짝꿍 */
    loud: string
    /**
     * E 작게 · 짝꿍 — 탓은 이야기 속 대상에게 · "내가 다시 해 볼게! 준비 완료!"로 끝난다 (아이에게 다시 시키지 않고 캐릭터가 시범).
     * 문장마다 자막을 나누면 목소리 파일도 quiet-1 · quiet-2 … (2026-11-27 우주비행사)
     */
    quiet: string | readonly string[]
    /** E 무음 · 이끔 — "내가 다시 해 볼게! 준비 완료!"로 끝난다 (아이에게 다시 시키지 않고 캐릭터가 시범) */
    silent: string
    /** 다시 말하기 · 짝꿍 (뒤에 이끔이 COMMON.retryLead) */
    retry: string
    /** G · 짝꿍 — 이야기가 한 걸음 나아간다 */
    bridge: string
    /** I · 둘이 같이 — 마무리 */
    outro: string
  }
  /** 장면 설명 — 그림이 오기 전 임시 판에 적는다 (시나리오 §2 표의 "장면" 칸) */
  scenes: Record<string, string>
  /** 레이어로 그리는 장면 — 있으면 장면 그림 파일 · 임시 판보다 먼저 쓴다 */
  layered?: Record<string, LayeredScene>
}

